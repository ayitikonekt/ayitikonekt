import 'package:flutter/material.dart';

/// Flutter no incluye traducciones Material oficiales para `ht`.
/// Este delegado proporciona las etiquetas internas de Material en inglés
/// mientras los textos propios de AyitiKonekt siguen mostrándose en kreyòl.
class HaitianMaterialLocalizationsDelegate
    extends LocalizationsDelegate<MaterialLocalizations> {
  const HaitianMaterialLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => locale.languageCode == 'ht';

  @override
  Future<MaterialLocalizations> load(Locale locale) async {
    return const DefaultMaterialLocalizations();
  }

  @override
  bool shouldReload(HaitianMaterialLocalizationsDelegate old) => false;
}

class AppLocaleProvider extends ChangeNotifier {
  Locale _locale = const Locale('es');
  String _languageName = 'Español';

  Locale get locale => _locale;
  String get languageName => _languageName;

  void selectLanguage({required String code, required String name}) {
    _locale = Locale(code);
    _languageName = name;
    notifyListeners();
  }

  void selectLanguageName(String name) {
    final normalized = name.toLowerCase();
    final code = normalized.contains('krey')
        ? 'ht'
        : normalized.contains('fran')
        ? 'fr'
        : normalized.contains('english')
        ? 'en'
        : normalized.contains('portugu')
        ? 'pt'
        : 'es';

    selectLanguage(code: code, name: name);
  }
}

extension AppTranslations on BuildContext {
  String tr(String key) {
    final code = Localizations.localeOf(this).languageCode;
    return _translations[code]?[key] ?? _translations['es']![key] ?? key;
  }

  String trWith(String key, Map<String, String> values) {
    var result = tr(key);
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', entry.value);
    }
    return result;
  }
}

